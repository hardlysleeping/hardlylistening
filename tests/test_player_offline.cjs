// Offline copies, end to end, without a window: the shell's `offline.js` is loaded into a vm with
// a real `fetch`, a real HTTP server that speaks Range, and a real temporary directory behind a
// shim that mirrors the commands in `player/src-tauri/src/offline.rs`.
//
// The Rust crate cannot be built on this machine (no webkit2gtk), so the filesystem rules — a
// name that cannot leave the account directory, a write that continues at an offset, a commit
// that refuses a short file — are exercised through the same contract those commands expose, and
// the pure name/decode rules are compiled on their own by `tests/test_player_offline.py`. What is
// proven here is the client: which tracks are kept, the resume from the byte a connection died
// at, the integrity check, the budget, the eviction order, and a play that never asks the server.
//
// Fixtures are a few KB of generated bytes. No audio, and no network beyond 127.0.0.1.
const fs = require("fs");
const http = require("http");
const os = require("os");
const path = require("path");
const vm = require("vm");

const SOURCE = fs.readFileSync(path.join(__dirname, "..", "player", "shell", "offline.js"), "utf8");

const SIZE = 4000;
const ACCOUNT = { server: "https://music.example.com", username: "bazzite" };
const ACCOUNT_KEY = ACCOUNT.server + "|" + ACCOUNT.username;

let failures = 0;
function check(name, ok, detail) {
  if (ok) console.log("PASS " + name);
  else { failures++; console.log("FAIL " + name + (detail === undefined ? "" : " — " + detail)); }
}

function fixture(id, size = SIZE) {
  const body = Buffer.alloc(size);
  const seed = String(id).charCodeAt(0) || 65;
  for (let i = 0; i < size; i += 1) body[i] = (i * 31 + seed * 7) & 0xff;
  return body;
}

function memoryStorage() {
  const map = new Map();
  return {
    map,
    getItem: key => (map.has(key) ? map.get(key) : null),
    setItem: (key, value) => map.set(key, String(value)),
    removeItem: key => map.delete(key),
  };
}

// ---- the stub server ------------------------------------------------------
// One route, `/rest/stream.view?id=…`. It honours Range, sends an ETag and a Content-Length, and
// can be told to drop the connection part-way through a body (once, or every time), to stall so
// only a cancel can end the download, or to ignore Range and answer with the whole file.
const plans = new Map();
const requests = [];
const stalled = new Set();

function planFor(id) {
  if (!plans.has(id)) {
    plans.set(id, { etag: '"v1"', dropAt: null, repeat: false, stallAfter: null, ignoreRange: false });
  }
  return plans.get(id);
}

function startServer() {
  const server = http.createServer((req, res) => {
    const url = new URL(req.url, "http://stub");
    if (url.pathname !== "/rest/stream.view") {
      res.writeHead(404, { "content-type": "text/plain" }).end("no");
      return;
    }
    const id = String(url.searchParams.get("id") || "");
    const body = fixture(id);
    const plan = planFor(id);
    const header = String(req.headers.range || "").trim();
    const match = /^bytes=(\d+)-(\d*)$/.exec(header);
    requests.push({ id: id, range: header || null });
    const start = match ? Number(match[1]) : 0;
    const end = match && match[2] ? Math.min(Number(match[2]), body.length - 1) : body.length - 1;
    const etag = plan.etag ? { etag: plan.etag } : {};
    if (plan.ignoreRange && match) {
      // The one answer a resume must not paper over: the file, from zero.
      res.writeHead(200, Object.assign({
        "content-type": "audio/mpeg", "accept-ranges": "bytes",
        "content-length": String(body.length),
      }, etag));
      res.end(body);
      return;
    }
    const headers = Object.assign({
      "content-type": "audio/mpeg", "accept-ranges": "bytes",
      "content-length": String(end - start + 1),
    }, etag);
    if (match) headers["content-range"] = "bytes " + start + "-" + end + "/" + body.length;
    res.writeHead(match ? 206 : 200, headers);
    if (plan.dropAt !== null) {
      // A body that stops at a byte while the headers still promise the whole file: the client
      // has no way to call this complete, only to resume from what it has.
      const stop = Math.min(plan.dropAt, end + 1);
      if (!plan.repeat) plan.dropAt = null;
      if (start >= stop) { res.end(); return; }
      res.end(body.subarray(start, stop));
      return;
    }
    if (plan.stallAfter !== null && start >= plan.stallAfter) {
      // Bytes stop arriving and the connection stays open: only a cancel ends this.
      stalled.add(res);
      res.on("close", () => stalled.delete(res));
      return;
    }
    res.end(body.subarray(start, end + 1));
  });
  return new Promise(resolve => {
    server.listen(0, "127.0.0.1", () => resolve({
      server: server, base: "http://127.0.0.1:" + server.address().port,
    }));
  });
}

// ---- the store shim -------------------------------------------------------
// Mirrors `offline.rs` command for command: a per-account directory, `<name>.part` until the
// length matches, a manifest written through a temporary file, strict offsets, and a name that is
// sanitised before it is joined.
function makeStore(api, root) {
  const dirFor = account => {
    if (!String(account || "").trim()) throw new Error("no account was named");
    const dir = path.join(root, api.accountName(account));
    fs.mkdirSync(dir, { recursive: true });
    return dir;
  };
  const manifestPath = dir => path.join(dir, "manifest.json");
  const readManifest = dir => {
    try {
      const raw = JSON.parse(fs.readFileSync(manifestPath(dir), "utf8"));
      if (raw && raw.entries && typeof raw.entries === "object") return raw;
    } catch (error) { /* a missing or unreadable manifest is an empty one */ }
    return { version: 1, entries: {} };
  };
  const writeManifest = (dir, manifest) => {
    const temp = manifestPath(dir) + ".part";
    fs.writeFileSync(temp, JSON.stringify(manifest, null, 2) + "\n");
    fs.renameSync(temp, manifestPath(dir));
  };
  const entryFile = (dir, entry) => {
    const own = api.safeComponent(entry.file || "");
    const name = own
      || (entry.key && entry.suffix
        ? api.safeComponent(String(entry.key)) + "." + api.safeSuffix(String(entry.suffix))
        : null);
    if (!name) throw new Error("that manifest entry does not name a usable file");
    const target = path.join(dir, name);
    if (path.dirname(target) !== dir) {
      throw new Error("that manifest entry points outside the account's directory");
    }
    return target;
  };
  const entryFor = (dir, key) => readManifest(dir).entries[api.safeComponent(String(key))];

  const invoke = async (name, args) => {
    const input = args || {};
    switch (name) {
      case "offline_manifest":
        return readManifest(dirFor(input.account));
      case "offline_begin": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        if (!key) throw new Error("this player cannot use that as a file name");
        const file = key + "." + api.safeSuffix(input.suffix);
        const part = path.join(dir, file + ".part");
        if (!fs.existsSync(part)) fs.writeFileSync(part, Buffer.alloc(0));
        return { file: file, partial: fs.statSync(part).size };
      }
      case "offline_write": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        if (!key) throw new Error("this player cannot use that as a file name");
        const part = path.join(dir, key + "." + api.safeSuffix(input.suffix) + ".part");
        const bytes = Buffer.from(String(input.data), "base64");
        // An independent encoder, so a broken base64 in the client cannot pass unnoticed.
        if (bytes.toString("base64").replace(/=+$/, "") !== String(input.data).replace(/=+$/, "")) {
          throw new Error("the chunk was not base64");
        }
        const held = fs.statSync(part).size;
        if (Number(input.offset) !== held) {
          throw new Error("the store holds " + held + " bytes and the chunk claimed to start at "
            + input.offset);
        }
        fs.appendFileSync(part, bytes);
        return { written: bytes.length, partial: held + bytes.length };
      }
      case "offline_commit": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        if (!key) throw new Error("this player cannot use that as a file name");
        const entry = input.entry || {};
        const file = key + "." + api.safeSuffix(input.suffix);
        const part = path.join(dir, file + ".part");
        const target = path.join(dir, file);
        if (path.dirname(part) !== dir || path.dirname(target) !== dir) {
          throw new Error("that name does not belong in the account's directory");
        }
        if (!fs.existsSync(part)) throw new Error("there is no partial copy to commit");
        const held = fs.statSync(part).size;
        const declared = Number(entry.size) || 0;
        if (!declared || held !== declared) {
          throw new Error("the copy on disk is " + held + " bytes and the manifest claims "
            + declared);
        }
        fs.renameSync(part, target);
        const manifest = readManifest(dir);
        manifest.entries[key] = {
          file: file, key: key, suffix: api.safeSuffix(input.suffix), size: held,
          expected: held, etag: entry.etag || null, contentType: entry.contentType || null,
          title: entry.title || null, sourceSize: entry.sourceSize === undefined ? null : entry.sourceSize,
          addedAt: entry.addedAt === undefined ? null : entry.addedAt,
          lastPlayed: entry.lastPlayed === undefined ? null : entry.lastPlayed,
          complete: true,
        };
        writeManifest(dir, manifest);
        return { ok: true, file: file, size: held };
      }
      case "offline_pin": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        if (!key) throw new Error("this player cannot use that as a file name");
        const file = key + "." + api.safeSuffix(input.suffix);
        const manifest = readManifest(dir);
        manifest.entries[key] = {
          file: file, key: key, suffix: api.safeSuffix(input.suffix),
          size: fs.existsSync(path.join(dir, file + ".part")) ? fs.statSync(path.join(dir, file + ".part")).size : 0,
          expected: input.expected === undefined ? null : input.expected,
          etag: input.etag || null, contentType: null, title: null, sourceSize: null,
          addedAt: null, lastPlayed: 0, complete: false,
        };
        writeManifest(dir, manifest);
        return { ok: true };
      }
      case "offline_touch": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        const manifest = readManifest(dir);
        if (!manifest.entries[key]) return { ok: false };
        manifest.entries[key].lastPlayed = Number(input.at) || 0;
        writeManifest(dir, manifest);
        return { ok: true };
      }
      case "offline_stat": {
        const dir = dirFor(input.account);
        const entry = entryFor(dir, input.key);
        if (!entry) return { ok: true, exists: false, bytes: null };
        const target = entryFile(dir, entry);
        if (!fs.existsSync(target)) return { ok: true, exists: false, bytes: null };
        return { ok: true, exists: true, bytes: fs.statSync(target).size };
      }
      case "offline_read": {
        const dir = dirFor(input.account);
        const entry = entryFor(dir, input.key);
        if (!entry) throw new Error("no copy of that track is kept");
        const target = entryFile(dir, entry);
        const size = fs.statSync(target).size;
        const offset = Number(input.offset) || 0;
        if (offset > size) throw new Error("that read starts past the end of the copy");
        const want = Math.min(Number(input.length) || size, 4 * 1024 * 1024, size - offset);
        const buffer = Buffer.alloc(want);
        const handle = fs.openSync(target, "r");
        fs.readSync(handle, buffer, 0, want, offset);
        fs.closeSync(handle);
        return { data: buffer.toString("base64"), offset: offset, eof: offset + want >= size };
      }
      case "offline_delete": {
        const dir = dirFor(input.account);
        const key = api.safeComponent(input.key);
        if (!key) throw new Error("this player cannot use that as a file name");
        const manifest = readManifest(dir);
        let removed = false;
        if (manifest.entries[key]) {
          try { fs.unlinkSync(entryFile(dir, manifest.entries[key])); } catch (error) { /* gone */ }
          delete manifest.entries[key];
          removed = true;
        }
        let partials = 0;
        for (const name of fs.readdirSync(dir)) {
          const target = path.join(dir, name);
          if (name.startsWith(key + ".") && name.endsWith(".part") && path.dirname(target) === dir) {
            fs.unlinkSync(target);
            partials += 1;
          }
        }
        if (removed || partials) writeManifest(dir, manifest);
        return { ok: true, removed: removed, partials: partials };
      }
      case "offline_free":
        return { available: 90 * 1024 * 1024 * 1024, total: 400 * 1024 * 1024 * 1024, reason: null };
      default:
        throw new Error("unknown command " + name);
    }
  };

  return {
    invoke: invoke,
    dir: account => path.join(root, api.accountName(account)),
    manifest: account => readManifest(dirFor(account)),
    files: account => fs.readdirSync(dirFor(account)).sort(),
    // What the dialog would call "kept": a pinned partial is a download in flight, not a copy.
    kept: account => {
      const entries = readManifest(dirFor(account)).entries;
      return Object.keys(entries).filter(key => entries[key] && entries[key].complete !== false)
        .sort().join(",");
    },
    tree: () => {
      const found = [];
      const walk = dir => {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
          const full = path.join(dir, entry.name);
          if (entry.isDirectory()) walk(full);
          else found.push(path.relative(root, full));
        }
      };
      walk(root);
      return found.sort();
    },
  };
}

// One sandbox is one device: its own directory, its own budget, its own module instance.
function sandbox(base, options) {
  const input = options || {};
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "player-offline-"));
  const storage = memoryStorage();
  const created = [];
  const calls = [];
  const state = { now: 1000 };
  const context = {
    Promise: Promise, Uint8Array: Uint8Array, TextEncoder: TextEncoder,
    AbortController: AbortController,
    URL: { createObjectURL: () => "blob:stub", revokeObjectURL: () => { } },
    console: console,
    localStorage: storage,
    fetch: async (url, settings) => {
      calls.push({ url: String(url), headers: (settings || {}).headers || {} });
      return fetch(url, settings);
    },
  };
  vm.createContext(context);
  vm.runInContext(SOURCE, context, { filename: "offline.js" });
  const api = vm.runInContext("this.PlayerOffline", context);
  const store = makeStore(api, root);
  api.configure({
    account: ACCOUNT,
    fetch: context.fetch,
    invoke: input.invoke || store.invoke,
    streamUrl: track => base + "/rest/stream.view?id=" + encodeURIComponent(track.id),
    createUrl: (bytes, type) => {
      created.push({ bytes: Buffer.from(bytes), type: type });
      return "blob:stub/" + created.length;
    },
    storage: input.storage || storage,
    now: () => (input.clock ? input.clock() : state.now),
  });
  return {
    api: api, store: store, storage: storage, calls: calls, created: created, state: state,
    root: root,
    tick: by => { state.now += by === undefined ? 1000 : by; return state.now; },
    keep: id => path.join(store.dir(ACCOUNT_KEY), id + ".mp3"),
    cleanup: () => fs.rmSync(root, { recursive: true, force: true }),
  };
}

async function main() {
  const { server, base } = await startServer();

  // ---- the names --------------------------------------------------------
  {
    const device = sandbox(base);
    const accepted = ["abc123", "a.b", "track_1-2", "A".repeat(64)];
    check("a name this player can write is accepted",
      accepted.every(name => device.api.safeComponent(name) === name), accepted.join(" "));
    const hostile = ["", "..", ".", "../etc/passwd", "a/b", "a\\b", "C:evil.mp3", "x\u0000y",
      "\u00e9t\u00e9", "a".repeat(65), "./x", "..\\..\\x", "/etc/passwd"];
    const allowed = hostile.filter(name => device.api.safeComponent(name) !== null);
    check("a hostile track id is not a name", allowed.length === 0, JSON.stringify(allowed));
    check("a suffix cannot carry a path",
      device.api.safeSuffix("../x") === "x" && device.api.safeSuffix("") === "bin"
        && device.api.safeSuffix(".MP3") === "mp3"
        && device.api.safeSuffix("../../etc/passwd") === "bin",
      device.api.safeSuffix("../../etc/passwd"));
    check("the account directory is ascii, stable and per account",
      /^[a-z0-9_-]+$/.test(device.api.accountName(ACCOUNT_KEY))
        && device.api.accountName(ACCOUNT_KEY) === device.api.accountName(ACCOUNT_KEY)
        && device.api.accountName("https://a/b|c") !== device.api.accountName("https://a_b|c"),
      device.api.accountName(ACCOUNT_KEY));
    check("base64 survives both ways",
      Buffer.from(device.api.decodeBase64(device.api.encodeBase64(Buffer.from([0, 1, 2, 250, 255, 7]))))
        .equals(Buffer.from([0, 1, 2, 250, 255, 7]))
        && device.api.encodeBase64(Buffer.from("hello")) === "aGVsbG8=");
    device.cleanup();
  }

  // ---- a hostile id never reaches the store ----------------------------
  {
    const device = sandbox(base);
    const before = device.store.tree().length;
    let refused = 0;
    for (const id of ["../../etc/passwd", "a/b", "..", "C:\\evil.mp3", "", "x".repeat(65)]) {
      const result = await device.api.download({ id: id, suffix: "mp3" });
      if (!result.ok) refused += 1;
    }
    check("a download for a hostile id is refused", refused === 6, String(refused));
    check("and nothing was written", device.store.tree().length === before &&
      !fs.existsSync(path.join(device.root, "..", "..", "etc")), device.store.tree().join(","));
    let threw = false;
    try {
      await device.store.invoke("offline_begin", { account: ACCOUNT_KEY, key: "../escape", suffix: "mp3" });
    } catch (error) {
      threw = /file name|outside/.test(error.message);
    }
    check("the store refuses the same name when asked directly", threw);
    device.cleanup();
  }

  // ---- a clean download -------------------------------------------------
  {
    const device = sandbox(base);
    planFor("clean").dropAt = null;
    const result = await device.api.download({ id: "clean", suffix: "mp3", size: SIZE, title: "Clean" });
    check("a whole file is kept", result.ok && result.bytes === SIZE && result.resumedFrom === 0,
      JSON.stringify(result));
    check("the first request asked for no range",
      device.calls.length === 1 && !device.calls[0].headers.Range,
      JSON.stringify(device.calls.map(call => call.headers)));
    check("the kept file is the server's bytes",
      fs.readFileSync(device.keep("clean")).equals(fixture("clean")), device.keep("clean"));
    check("no partial is left behind", !fs.existsSync(device.keep("clean") + ".part"),
      device.store.files(ACCOUNT_KEY).join(","));
    const entry = device.store.manifest(ACCOUNT_KEY).entries.clean;
    check("the manifest records a complete copy with its size and etag",
      !!entry && entry.complete === true && entry.size === SIZE && entry.etag === '"v1"',
      JSON.stringify(entry));
    device.cleanup();
  }

  // ---- an interrupted download resumes at the byte it stopped at -------
  {
    const broken = sandbox(base);
    planFor("resume").dropAt = 1000;
    planFor("resume").repeat = false;
    const first = await broken.api.download({ id: "resume", suffix: "mp3" });
    const ranges = broken.calls.map(call => call.headers.Range || null);
    check("a connection that died mid-body is resumed, not restarted",
      first.ok && ranges[0] === null && ranges[1] === "bytes=1000-",
      JSON.stringify({ result: first, ranges: ranges }));
    const resumed = fs.readFileSync(broken.keep("resume"));
    check("the resumed file is the whole fixture", resumed.equals(fixture("resume")),
      String(resumed.length));

    // The same track, on a device that never lost the connection.
    const clean = sandbox(base);
    const second = await clean.api.download({ id: "resume", suffix: "mp3" });
    check("and byte-identical to a clean download of the same track",
      second.ok && second.resumedFrom === 0
        && fs.readFileSync(clean.keep("resume")).equals(resumed),
      JSON.stringify(second));
    check("a resume does not change the accounted size",
      broken.store.manifest(ACCOUNT_KEY).entries.resume.size === SIZE,
      String(broken.store.manifest(ACCOUNT_KEY).entries.resume.size));
    broken.cleanup();
    clean.cleanup();
  }

  // ---- a cancel, and the resume from where it stopped ------------------
  {
    const device = sandbox(base);
    planFor("cancelled").stallAfter = 1000;
    let handle = null;
    let at = 0;
    handle = device.api.start({ id: "cancelled", suffix: "mp3" }, {
      onProgress: progress => {
        at = progress.received;
        if (handle) handle.cancel();
      },
    });
    const result = await handle.promise;
    check("a cancelled download stops and says where",
      result.ok === false && result.cancelled === true && at > 0, JSON.stringify(result));
    const partial = device.keep("cancelled") + ".part";
    check("the partial is kept for the next attempt",
      fs.existsSync(partial) && fs.statSync(partial).size === at,
      fs.existsSync(partial) ? String(fs.statSync(partial).size) : "missing");
    check("and it is not listed as a kept track", device.store.kept(ACCOUNT_KEY) === "",
      device.store.kept(ACCOUNT_KEY));

    planFor("cancelled").stallAfter = null;
    for (const response of stalled) response.destroy();
    stalled.clear();
    device.calls.length = 0;
    const again = await device.api.download({ id: "cancelled", suffix: "mp3" });
    check("the next attempt continues from that byte",
      again.ok && again.resumedFrom === at && device.calls[0].headers.Range === "bytes=" + at + "-",
      JSON.stringify({ result: again, first: device.calls[0] && device.calls[0].headers }));
    check("and lands on the server's bytes",
      fs.readFileSync(device.keep("cancelled")).equals(fixture("cancelled")));
    device.cleanup();
  }

  // ---- a truncated file is never accepted as complete ------------------
  {
    const device = sandbox(base);
    planFor("short").dropAt = 1200;
    planFor("short").repeat = true;
    const result = await device.api.download({ id: "short", suffix: "mp3" });
    check("a body that keeps ending early is not kept",
      result.ok === false && result.truncated === true && device.store.kept(ACCOUNT_KEY) === "",
      JSON.stringify(result));
    check("what it did receive stays as a partial",
      fs.existsSync(device.keep("short") + ".part"));
    const play = await device.api.local({ id: "short", suffix: "mp3" });
    check("and playing it is refused rather than half-played", play.ok === false,
      JSON.stringify(play));

    // A copy that was complete and was cut short on disk afterwards.
    planFor("cut").dropAt = null;
    const kept = await device.api.download({ id: "cut", suffix: "mp3" });
    fs.truncateSync(device.keep("cut"), 100);
    device.calls.length = 0;
    const after = await device.api.local({ id: "cut", suffix: "mp3" });
    check("a kept file that is shorter than the manifest is detected",
      kept.ok && after.ok === false && /truncated/.test(after.reason), JSON.stringify(after));
    check("and it is dropped instead of played",
      !fs.existsSync(device.keep("cut")) && !device.store.manifest(ACCOUNT_KEY).entries.cut
        && device.store.kept(ACCOUNT_KEY) === "",
      device.store.files(ACCOUNT_KEY).join(","));
    check("which needed no request", device.calls.length === 0, String(device.calls.length));
    device.cleanup();
  }

  // ---- a resume the server cannot honour -------------------------------
  {
    const device = sandbox(base);
    planFor("ignore").dropAt = 900;
    planFor("ignore").repeat = true;
    await device.api.download({ id: "ignore", suffix: "mp3" });
    check("a failed attempt leaves a partial",
      fs.existsSync(device.keep("ignore") + ".part") && device.store.kept(ACCOUNT_KEY) === "",
      device.store.kept(ACCOUNT_KEY));
    planFor("ignore").repeat = false;
    planFor("ignore").dropAt = null;
    planFor("ignore").ignoreRange = true;
    device.calls.length = 0;
    const result = await device.api.download({ id: "ignore", suffix: "mp3" });
    const ranges = device.calls.map(call => call.headers.Range || null);
    check("a server that answers 200 to a range is restarted from zero",
      result.ok && ranges.includes("bytes=900-") && ranges.includes(null), JSON.stringify(ranges));
    check("and the file is whole", fs.readFileSync(device.keep("ignore")).equals(fixture("ignore")));

    planFor("tagged").dropAt = 800;
    planFor("tagged").repeat = true;
    await device.api.download({ id: "tagged", suffix: "mp3" });
    planFor("tagged").repeat = false;
    planFor("tagged").dropAt = null;
    planFor("tagged").etag = '"v2"';
    device.calls.length = 0;
    const stitched = await device.api.download({ id: "tagged", suffix: "mp3" });
    const once = device.calls.map(call => call.headers.Range || null);
    check("a changed ETag restarts rather than stitches",
      stitched.ok && once[0] === "bytes=800-" && once.includes(null), JSON.stringify(once));
    check("and the file is whole", fs.readFileSync(device.keep("tagged")).equals(fixture("tagged")));
    device.cleanup();
  }

  // ---- the budget and the eviction rule -------------------------------
  {
    const device = sandbox(base);
    for (const id of ["a", "b", "c", "d", "e"]) planFor(id).dropAt = null;

    await device.api.setBudget(0);
    const off = await device.api.download({ id: "a", suffix: "mp3" });
    check("with the budget off nothing is downloaded",
      off.ok === false && /switched off/.test(off.reason), JSON.stringify(off));

    await device.api.setBudget(3 * SIZE);
    for (const id of ["a", "b", "c"]) { device.tick(); await device.api.download({ id: id, suffix: "mp3" }); }
    const full = await device.api.stats();
    check("three tracks fit a budget of three", device.store.kept(ACCOUNT_KEY) === "a,b,c",
      device.store.kept(ACCOUNT_KEY));
    check("and the total is inside the budget", full.bytes <= 3 * SIZE && full.count === 3,
      JSON.stringify(full));

    await device.api.setBudget(2 * SIZE);
    const trimmed = await device.api.stats();
    check("the oldest played copy is the one evicted", device.store.kept(ACCOUNT_KEY) === "b,c",
      device.store.kept(ACCOUNT_KEY));
    check("and the total is back inside the budget", trimmed.bytes <= 2 * SIZE, String(trimmed.bytes));

    // The track that is playing survives eviction even when it is the oldest.
    device.tick();
    await device.api.download({ id: "a", suffix: "mp3" });
    device.tick();
    await device.api.download({ id: "d", suffix: "mp3" });
    const kept = device.store.manifest(ACCOUNT_KEY).entries;
    check("a and d are kept, b and c are not",
      Object.keys(kept).sort().join(",") === "a,d", Object.keys(kept).sort().join(","));
    device.tick();
    const playing = await device.api.download({ id: "e", suffix: "mp3" }, { playing: "a" });
    const after = device.store.manifest(ACCOUNT_KEY).entries;
    check("eviction never removes the playing track",
      !!after.a && !playing.evicted.includes("a")
        && Object.keys(after).sort().join(",") === "a,e",
      JSON.stringify({ evicted: playing.evicted, kept: Object.keys(after).sort() }));
    check("and the budget is still met", (await device.api.stats()).bytes <= 2 * SIZE,
      JSON.stringify(await device.api.stats()));

    // A track larger than the whole budget is refused and not left on disk.
    await device.api.setBudget(SIZE - 1);
    const big = await device.api.download({ id: "b", suffix: "mp3" });
    check("a track larger than the budget is not kept",
      big.ok === false && /larger than the whole budget/.test(big.reason), JSON.stringify(big));
    check("and it is not left behind", device.store.kept(ACCOUNT_KEY) === "",
      device.store.kept(ACCOUNT_KEY));

    await device.api.setBudget(2 * SIZE);
    device.tick();
    await device.api.download({ id: "c", suffix: "mp3" });
    check("a track that fits is kept again", device.store.kept(ACCOUNT_KEY) === "c",
      device.store.kept(ACCOUNT_KEY));
    await device.api.setBudget(0);
    check("switching the budget off removes the copies",
      device.store.kept(ACCOUNT_KEY) === "" && device.store.files(ACCOUNT_KEY).join(",") === "manifest.json",
      device.store.files(ACCOUNT_KEY).join(","));
    device.cleanup();
  }

  // ---- playing a kept copy asks the server nothing --------------------
  {
    const device = sandbox(base);
    planFor("played").dropAt = null;
    await device.api.download({ id: "played", suffix: "mp3" });
    device.calls.length = 0;
    const source = await device.api.local({ id: "played", suffix: "mp3" });
    check("a kept track plays from its copy",
      source.ok && source.size === SIZE && /^blob:/.test(source.url), JSON.stringify(source));
    check("without one request to the server", device.calls.length === 0,
      String(device.calls.length));
    check("and the bytes handed over are the file",
      device.created.length === 1 && device.created[0].bytes.equals(fixture("played")));
    await device.api.setBudget(SIZE * 4);
    const written = Array.from(device.storage.map.entries());
    check("no credential is written: the budget is the only stored key",
      written.length === 1 && written[0][0] === device.api.BUDGET_KEY
        && !written.some(pair => /bazzite|music\.example\.com|s3cret/.test(pair[0] + pair[1])),
      JSON.stringify(written));
    const free = await device.api.freeSpace();
    check("free space is reported rather than guessed", free.available > 0, JSON.stringify(free));

    // A track the store knows nothing about is not played from nowhere.
    const missing = await device.api.local({ id: "never-downloaded", suffix: "mp3" });
    check("an unkept track has no local copy", missing.ok === false && device.calls.length === 0,
      JSON.stringify(missing));
    device.cleanup();
  }

  // ---- cleanup ---------------------------------------------------------
  for (const response of stalled) response.destroy();
  stalled.clear();
  await new Promise(resolve => server.close(resolve));

  if (failures) {
    console.log(failures + " failed");
    process.exit(1);
  }
  console.log("all offline checks passed");
}

main().catch(error => {
  console.log("FAIL the harness threw — " + (error && error.stack || error));
  process.exit(1);
});