"""PLAYER-001: the player is a Tauri 2 shell that talks to any Subsonic server.

Two halves, because either alone can be fooled:

  * **Static** — `tauri.conf.json` and the capability file are the ones Tauri 2 reads (the
    window opens at the connect screen, the front end is the assembled tree, the capability
    grants the core and nothing else), and the assembly's allow-list is the only statement of
    what the player bundles.
  * **Runtime** — `assemble.mjs` is run into a temporary directory and its output is walked.
    "No acquisition module ships" is then a fact about files on disk, not a comment in a
    source tree; every file but the entry document is hashed against `web/` to prove nothing
    was rewritten on the way in, and the entry document is proven to differ from its source by
    exactly the references the receipt says were dropped.

The player is a client, so it also has to stay a separate tree: nothing under `player/` may
reach `desktop/` (another shippable) or import the server's Python. That is asserted here as
well as by `tests/test_headless.py`, which is what keeps `player/` from turning into a host
the core needs.
"""
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

APP_DIR = Path(__file__).resolve().parents[1]
PLAYER = APP_DIR / 'player'
TAURI = PLAYER / 'src-tauri'
ASSEMBLE = PLAYER / 'assemble.mjs'
NODE = shutil.which('node')

CODE_SUFFIXES = {'.rs', '.js', '.mjs', '.html', '.css', '.json', '.toml'}
#: What the player must never reach for. The host shell is a separate artefact, and the
#: server is something a player talks to over HTTP, never imports.
FOREIGN = ('desktop/', 'from desktop', 'import desktop', 'server.py', 'listening.py',
           'subsonic.py', 'sys.path')


def run_node(*args, cwd=APP_DIR):
    if not NODE:
        raise unittest.SkipTest('node is not on PATH')
    return subprocess.run([NODE, *args], cwd=cwd, capture_output=True, text=True, timeout=120)


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def player_sources():
    for path in sorted(PLAYER.rglob('*')):
        if not path.is_file() or path.suffix not in CODE_SUFFIXES:
            continue
        parts = path.relative_to(PLAYER).parts
        if parts[0] in ('www', 'target', 'gen'):
            continue
        yield path


class TauriConfiguration(unittest.TestCase):
    """The shell is configured for desktop, iOS and Android from one file."""

    @classmethod
    def setUpClass(cls):
        cls.config = json.loads((TAURI / 'tauri.conf.json').read_text())
        cls.capabilities = [json.loads(path.read_text())
                            for path in sorted((TAURI / 'capabilities').glob('*.json'))]

    def test_the_window_opens_at_the_connect_screen(self):
        windows = self.config['app']['windows']
        self.assertEqual(len(windows), 1)
        self.assertEqual(windows[0]['label'], 'main')
        self.assertEqual(windows[0]['url'], 'connect.html')

    def test_the_front_end_is_the_assembled_tree_and_the_assembly_runs_first(self):
        build = self.config['build']
        self.assertEqual(build['frontendDist'], '../www')
        self.assertIn('assemble.mjs', build['beforeBuildCommand'])
        self.assertIn('assemble.mjs', build['beforeDevCommand'])

    def test_desktop_and_mobile_targets_are_declared(self):
        bundle = self.config['bundle']
        self.assertTrue(bundle['active'])
        self.assertEqual(bundle['targets'], 'all')
        self.assertIn('minimumSystemVersion', bundle['iOS'])
        self.assertGreaterEqual(int(bundle['android']['minSdkVersion']), 24)

    def test_capabilities_grant_the_core_and_nothing_else(self):
        self.assertTrue(self.capabilities, 'no capability file means no window can load')
        for capability in self.capabilities:
            self.assertEqual(capability['windows'], ['main'])
            self.assertTrue(capability['permissions'])
            for permission in capability['permissions']:
                self.assertTrue(permission.startswith('core:'),
                                f'{permission} is a plugin permission the shell does not use')

    def test_cargo_is_tauri_2_and_builds_a_library_mobile_can_link(self):
        text = (TAURI / 'Cargo.toml').read_text()
        self.assertIn('tauri-build = { version = "2"', text)
        self.assertIn('tauri = { version = "2"', text)
        crate = re.search(r'crate-type = \[(.*?)\]', text).group(1)
        for kind in ('staticlib', 'cdylib', 'rlib'):
            self.assertIn(kind, crate)

    def test_no_generated_mobile_project_is_checked_in(self):
        for platform in ('apple', 'android'):
            self.assertFalse((TAURI / 'gen' / platform).exists(),
                             f'gen/{platform} is generated by the Tauri CLI, not committed')
        # The docs have to say so, because the generated project is not here to read.
        docs = (APP_DIR / 'docs' / 'player.md').read_text()
        self.assertIn('tauri ios init', docs)
        self.assertIn('tauri android init', docs)


class Assembly(unittest.TestCase):
    """The allow-list is the single source of truth, and the script enforces it."""

    @classmethod
    def setUpClass(cls):
        result = run_node(str(ASSEMBLE), '--list')
        if result.returncode != 0:
            raise AssertionError(f'--list failed: {result.stderr}')
        cls.plan = json.loads(result.stdout)

    def test_every_listed_file_exists(self):
        missing = [rel for rel in self.plan['web'] if not (APP_DIR / 'web' / rel).is_file()]
        missing += [rel for rel in self.plan['shell'] if not (PLAYER / 'shell' / rel).is_file()]
        self.assertEqual(missing, [], 'the allow-list names files that are not there')

    def test_the_acquisition_module_is_not_in_the_allow_list(self):
        self.assertNotIn('js/repo-discovery.js', self.plan['web'])
        self.assertFalse(any(rel.endswith('repo-discovery.js') for rel in self.plan['web']))
        # Excluded by name, so the omission is a statement and not an oversight.
        excluded = dict((rel, why) for rel, why in self.plan['excluded'])
        self.assertIn('js/repo-discovery.js', excluded)
        self.assertIn('repo-discovery.js', self.plan['forbidden'])

    def test_the_library_player_and_visual_language_are_listed(self):
        allow = set(self.plan['web'])
        for rel in ('index.html', 'js/library.js', 'js/playback-queue.js', 'js/social-feed.js',
                    'styles/app.css', 'styles/tokens.css', 'styles/components/player.css',
                    'styles/components/queue-view.css'):
            self.assertIn(rel, allow)
            self.assertTrue((APP_DIR / 'web' / rel).is_file(), rel)

    def test_the_assembly_writes_a_tree_with_no_forbidden_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out))
            self.assertEqual(result.returncode, 0, result.stderr)
            files = [path.relative_to(out).as_posix()
                     for path in out.rglob('*') if path.is_file()]
            self.assertTrue(files)
            for rel in files:
                name = rel.rsplit('/', 1)[-1]
                self.assertNotIn('repo-discovery', name, rel)
                self.assertNotIn('src-tauri', rel.split('/'), rel)
                self.assertNotIn('node_modules', rel.split('/'), rel)
                self.assertNotIn('electron', name.lower(), rel)
                self.assertFalse(name.endswith('.py'), rel)
            # The app's own markup and the shell's entry are both there, and nothing else
            # is a page: a player has exactly one screen until PLAYER-003.
            self.assertIn('index.html', files)
            self.assertIn('connect.html', files)

    def test_copied_bytes_are_the_sources_bytes(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out))
            self.assertEqual(result.returncode, 0, result.stderr)
            # The entry document is the one rewritten file, and its exact difference is
            # asserted below; everything else has to arrive untouched.
            for rel in ('js/library.js', 'js/playback-queue.js',
                        'styles/app.css', 'styles/components/player.css'):
                self.assertEqual(sha256(out / rel), sha256(APP_DIR / 'web' / rel),
                                 f'{rel} was rewritten during assembly')

    def test_the_entry_document_requests_nothing_it_does_not_carry(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out))
            self.assertEqual(result.returncode, 0, result.stderr)
            page = (out / 'index.html').read_text()
            for reference in ('/js/repo-discovery.js', '/app.webmanifest', '/icon-192.png',
                              '/party', '/dj', '/swipe'):
                self.assertNotIn(reference, page,
                                 f'the assembled entry document still asks for {reference}')
            # The library, the queue and the app's stylesheet are still requested.
            for kept in ('/styles/app.css', '/js/library.js', '/js/playback-queue.js',
                         '/js/social-feed.js', '/preferences.js', '/lifecycle.js'):
                self.assertIn(kept, page)

    def test_the_receipt_records_each_drop_and_nothing_else_changed(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out))
            self.assertEqual(result.returncode, 0, result.stderr)
            receipt = json.loads((out / '.assembly.json').read_text())
            dropped = receipt['dropped']
            self.assertTrue(dropped, 'the entry document was rewritten without a receipt')
            self.assertEqual({drop['file'] for drop in dropped}, {'index.html'})
            self.assertIn('js/repo-discovery.js', {drop['path'] for drop in dropped})
            page = (out / 'index.html').read_text()
            for drop in dropped:
                self.assertNotIn(drop['value'], page, f'{drop["value"]} survived the drop')
            # Nothing else changed: the source minus the recorded removals is the output.
            expected = (APP_DIR / 'web' / 'index.html').read_text()
            for drop in dropped:
                self.assertIn(drop['removed'], expected, 'the receipt names text the source lacks')
                expected = expected.replace(drop['removed'], '', 1)
            self.assertEqual(expected, page, 'the entry document changed beyond the recorded drops')
            # And every other assembled file is still the source's own bytes.
            for rel in receipt['assembled']:
                if rel == 'index.html':
                    continue
                source = APP_DIR / 'web' / rel
                if not source.is_file():
                    source = PLAYER / 'shell' / rel
                self.assertEqual(sha256(out / rel), sha256(source), rel)

    def test_the_assembly_fails_when_a_referenced_file_is_forgotten(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            # `--forget-web` is the test hook that simulates an allow-list which forgot a file
            # the entry document still asks for: silence there would ship a broken page.
            result = run_node(str(ASSEMBLE), '--out', str(out), '--forget-web', 'js/library.js')
            self.assertEqual(result.returncode, 1)
            self.assertIn('js/library.js', result.stderr)
            self.assertIn('neither assembled nor excluded', result.stderr)
            self.assertFalse(out.exists(), 'a page with a dangling reference must not be written')

    def test_the_shell_entry_is_assembled_with_the_apps_stylesheets(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out))
            self.assertEqual(result.returncode, 0, result.stderr)
            page = (out / 'connect.html').read_text()
            self.assertIn('./connect.js', page)
            self.assertIn('./styles/tokens.css', page)
            self.assertIn('./styles/base.css', page)
            self.assertNotIn('<script>', page, 'the connect screen keeps its logic in connect.js')

    def test_the_assembly_fails_loudly_on_a_missing_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out), '--include-web', 'js/__missing__.js')
            self.assertEqual(result.returncode, 1)
            self.assertIn('__missing__.js', result.stderr)
            self.assertFalse(out.exists(), 'a bad plan must leave no half-built tree')

    def test_the_assembly_refuses_a_forbidden_module(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / 'www'
            result = run_node(str(ASSEMBLE), '--out', str(out), '--include-web', 'js/repo-discovery.js')
            self.assertEqual(result.returncode, 1)
            self.assertIn('repo-discovery.js', result.stderr)
            self.assertFalse(out.exists(), 'a forbidden module must not reach the tree')

    def test_the_assembly_refuses_to_write_into_web(self):
        target = APP_DIR / 'web' / 'player-assembly-must-not-exist'
        result = run_node(str(ASSEMBLE), '--out', str(target))
        self.assertEqual(result.returncode, 1)
        self.assertIn('web/', result.stderr)
        self.assertFalse(target.exists())

    def test_the_shell_directory_is_what_ships(self):
        # The shell is the player's own code: a file written there is in the build, so a
        # feature module cannot be added and then silently left out of the bundle.
        on_disk = sorted(p.name for p in (PLAYER / 'shell').iterdir() if p.is_file())
        self.assertEqual(self.plan['shell'], on_disk)
        self.assertIn('connect.html', self.plan['shell'])

    def test_the_output_directory_is_gitignored(self):
        # A deployed copy of the tree is not a git checkout and carries no ignore file, so
        # this is a property of the repository, not of the running server.
        ignore = APP_DIR / '.gitignore'
        if not ignore.is_file():
            self.skipTest('not a git checkout: no .gitignore to read')
        self.assertIn('player/www/', [line.strip() for line in ignore.read_text().splitlines()])


class Independence(unittest.TestCase):
    """A player is a client: it does not need the host shell or the server's code."""

    def test_the_player_is_a_tree_of_its_own(self):
        self.assertFalse((APP_DIR / 'src-tauri').exists(), 'the core must not gain a host shell')
        self.assertTrue((TAURI / 'tauri.conf.json').is_file())
        self.assertTrue(ASSEMBLE.is_file())
        self.assertTrue((PLAYER / 'shell' / 'connect.js').is_file())

    def test_the_player_reaches_neither_the_host_nor_the_server(self):
        offenders = []
        for path in player_sources():
            text = path.read_text(errors='replace')
            for needle in FOREIGN:
                if needle in text:
                    offenders.append(f'{path.relative_to(APP_DIR)}: {needle}')
        self.assertEqual(offenders, [], 'the player must not import the host or the server')

    def test_the_connect_screen_hands_the_secret_to_the_store_and_keeps_nothing(self):
        source = (PLAYER / 'shell' / 'connect.js').read_text()
        # Comments may name what is absent; statements may not reach for it. The connect page
        # itself never persists anything: the address and the username are a plain record and the
        # password's home is `accounts.js`, which writes it to the keychain or keeps it in memory.
        code = re.sub(r'/\*[\s\S]*?\*/', '', source)
        code = re.sub(r'^\s*//.*$', '', code, flags=re.M)
        for call in ('localStorage', 'sessionStorage', 'indexedDB', 'document.cookie',
                     'writeFile', 'setItem'):
            self.assertNotIn(call, code, f'{call} would put a password on disk')
        self.assertIn('/rest/ping.view', code)
        # The handoff, not a promise: PLAYER-002's module is loaded and given the credentials.
        self.assertIn('PlayerAccounts.open', code, 'the secret store has to be the one used')
        self.assertIn('accounts.migrate(session)', code, 'the session is handed over, not kept')


